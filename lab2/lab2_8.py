def task8():
    n = int(input("Введите количество учебных заданий (10-40): "))
    if n < 10 or n > 40:
        print("Число должно лежать в диапазоне 10-40")
    else:
        teens = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
                 "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
        tens = ["", "", "двадцать", "тридцать", "сорок"]
        units = ["", "одно", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
        if n < 20:
            number = teens[n - 10]
        elif n % 10 == 0:
            number = tens[n // 10]
        else:
            number = f"{tens[n // 10]} {units[n % 10]}"
        if 10 <= n <= 20 or n % 10 == 0 or n % 10 >= 5:
            words = "учебных заданий"
        elif n % 10 == 1:
            words = "учебное задание"
        else:
            words = "учебных задания"
        print(f"{n} - «{number} {words}»")

if __name__ == '__main__':
    task8()
