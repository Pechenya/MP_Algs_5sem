def task7():
    day = int(input("Введите номер дня (1-31): "))
    month = int(input("Введите номер месяца (1-12): "))
    days_in_month = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    if month < 1 or month > 12:
        print("Номер месяца должен лежать в диапазоне 1-12")
    elif day < 1 or day > days_in_month[month - 1]:
        print("В данном месяце нет такого дня")
    else:
        ordinals = ["", "первое", "второе", "третье", "четвертое", "пятое", "шестое", "седьмое",
                    "восьмое", "девятое", "десятое", "одиннадцатое", "двенадцатое", "тринадцатое",
                    "четырнадцатое", "пятнадцатое", "шестнадцатое", "семнадцатое", "восемнадцатое",
                    "девятнадцатое"]
        months = ["января", "февраля", "марта", "апреля", "мая", "июня",
                  "июля", "августа", "сентября", "октября", "ноября", "декабря"]
        if day < 20:
            day_text = ordinals[day]
        elif day == 20:
            day_text = "двадцатое"
        elif day == 30:
            day_text = "тридцатое"
        elif day < 30:
            day_text = f"двадцать {ordinals[day % 10]}"
        else:
            day_text = f"тридцать {ordinals[day % 10]}"
        print(f"{day_text} {months[month - 1]}")

if __name__ == '__main__':
    task7()
